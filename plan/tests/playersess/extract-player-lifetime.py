#!/usr/bin/env python3
"""Compile complete actual methods; reject missing/ambiguous anchors and bind bytes."""
import argparse
import hashlib
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--source', required=True)
parser.add_argument('--out', required=True)
args = parser.parse_args()
source = Path(args.source).resolve()
out = Path(args.out)
out.mkdir(parents=True, exist_ok=True)
repo = Path(__file__).resolve().parents[3]
control = source.read_text(encoding='utf-8-sig')
manifest = []
sha = lambda value: hashlib.sha256(value).hexdigest()


def extract(text, signature, origin=source):
    if text.count(signature) != 1:
        raise ValueError('expected exactly one anchor: ' + signature)
    start = text.index(signature)
    brace = text.index('{', start)
    match = re.search(r'\n        }(?=\n|$)', text[brace:])
    if not match:
        raise ValueError('missing method end: ' + signature)
    end = brace + match.end()
    body = text[start:end]
    manifest.append({
        'source': str(origin), 'signature': signature,
        'start_line': text[:start].count('\n') + 1,
        'end_line': text[:end].count('\n') + 1, 'sha256': sha(body.encode())
    })
    return body


signatures = [
    'public void InitializePlayInfo(', 'private async Task SetPlayItem(',
    'private void PlayerControl_Loaded(', 'private void PlayerControl_Unloaded(',
    'private void Player_PlayMediaOpened(', 'private void LoadPlayerSetting()',
    'private void LoadDanmuSetting()', 'private void LoadSutitleSetting()',
    'private async Task GetPlayerInfo()', 'private static bool IsAutoGeneratedSubtitle(',
    'private void SelectInitialSubtitle(', 'private void ClearSubTitle()',
    'private void SetSubTitle(string url)',
    'private async void SetSubTitle(string url, int generation)',
    'private async void LoadManifestSubtitleAsync(', 'public async void Dispose()',
    'private static string HistoryKey(', 'private async Task SetQuality()',
    'private async Task ChangeQuality(', 'private async Task<PlayerOpenResult> PlayLocalFile(',
    'private async Task ChangedNode(', 'private async Task SwitchLocalTrackAsync(',
    'private bool IsLocalSwitchItemCurrent(', 'private void EnsureLocalSwitchItem(',
    'private static string FormatLocalTrackSwitchFailure(',
    'private async void ImportDanmaku_Click(', 'private async void ImportSubtitle_Click(',
    'private async void ImportSingleDanmaku(', 'private async void ImportSingleSubtitle(',
    'private async Task SetDanmaku(', 'private async Task LoadDanmaku(',
    'private async void ManifestDanmakuTrack_Click(', 'private async void Player_ChangeEngine(',
    'private async Task ChangeEngineAsync(', 'public void ChangePlayIndex(',
    'private void Menuitem_Click('
]
parts = [extract(control, signature) for signature in signatures]
for signature in [
    'private bool IsPlaybackWorkCurrent(', 'private void UpdatePlaybackControlEligibility()',
    'private void DetachInteractionVideo()', 'private void ResetDanmakuWork('
]:
    # A helper may be absent in the old actual source; no substitute is manufactured.
    if signature in control:
        parts.append(extract(control, signature))
fields = []
for pattern in [
    r'^        private bool _disposed;', r'^        private bool _playerSettingsRegistered.*;',
    r'^        private bool _refreshingSettings;', r'^        private object _danmakuLoadLease;',
    r'^        private bool _danmakuInitialLoadPending;'
]:
    fields.extend(re.findall(pattern, control, re.M))
header = ('using System;using System.Linq;using System.Collections.Generic;'
          'using System.Threading.Tasks;using BiliLite.Services;'
          'using BiliLite.Services.LocalMedia;using Newtonsoft.Json;\n')
body = '\n'.join(fields + parts)
(out / 'PlayerLifetimeSlices.g.cs').write_text(
    header + 'namespace ResourceProbe { partial class ControlSubject {\n' + body + '\n}}\n')
renderer = extract(control, 'private async Task<Grid> GenerateSubtitleItem(')
(out / 'ActualScoped.g.cs').write_text(
    'using System;using System.Threading.Tasks;\nnamespace SubtitleGraphicsProbe {'
    ' class ActualScoped : FixtureOwner { public Task<Grid> Render(string text)'
    '=>GenerateSubtitleItem(text);\n' + renderer + '\n}}\n')

coordinator_path = repo / 'src/BiliLite.UWP/Services/LocalMedia/LocalMediaTrackSelection.cs'
coordinator = coordinator_path.read_text(encoding='utf-8-sig')
coordinator_body = extract(
    coordinator, 'public static async Task<LocalMediaTrackSwitchOutcome> SwitchAsync(',
    coordinator_path).replace('LocalPlayInfo info', 'LocalInfo info')
(out / 'TrackSwitchCoordinator.g.cs').write_text(
    'using System;using System.Threading.Tasks;namespace ResourceProbe {'
    'static class LocalMediaTrackSwitchCoordinator {' + coordinator_body + '}}')

# Separate namespace keeps the prior39 boundary controls intact while exercising the real child.
extra_signatures = [
    'private void UpdateLocalTrackSelectors()',
    'private async void LocalVideoTrackSelector_SelectionChanged(',
    'private async void LocalAudioTrackSelector_SelectionChanged(',
    'public void ShowTransitionPending(', 'public void ClearTransitionPending()',
    'private void ApplyNextLabel()', 'private async void DanmuTimer_Tick(',
    'private async void Player_PlayMediaEnded(',
    'private void UpdateBottomBtnNextVisibility()', 'private bool HasNextPart',
    'private async void DanmuSettingUpdateDanmaku_Click('
]
extra = '\n'.join(extract(control, signature) for signature in extra_signatures)
(out / 'PlayerResidualSlices.g.cs').write_text(
    'using System.Text.RegularExpressions;'
    'using BiliLite.Modules.Player;\n' + header +
    'namespace ResidualProbe { using Windows = global::ResidualWindows; partial class ControlSubject {\n' + body + '\n' + extra + '\n}}\n')

stub_path = Path(__file__).resolve().parent / 'PlayerLifetimeStubs.cs'
boundary = stub_path.read_text().replace('ResourceProbe', 'ResidualProbe')
boundary = boundary.replace('namespace Windows.', 'namespace ResidualWindows.')
start = boundary.index('    class InteractionVideoVM\n')
end = boundary.index('    class PlayerVM\n', start)
boundary = boundary[:start] + boundary[end:]
for signature in [
    'private void UpdateLocalTrackSelectors()', 'private void Player_PlayMediaEnded(',
    'private void UpdateBottomBtnNextVisibility()'
]:
    start = boundary.index(signature)
    end = boundary.index('\n        }', start) + 10
    boundary = boundary[:start] + boundary[end:]
boundary = 'using BiliLite.Modules.Player;\n' + boundary
boundary = boundary.replace('public string graph_version = "1";', 'public int graph_version = 1;')
boundary = boundary.replace('new InteractionVideoVM("1", "1")', 'new InteractionVideoVM("1", 1)')
for name in ['PlayerVM', 'PlayerStub', 'DanmakuStub', 'PlayInfo', 'Element',
             'LocalInfo', 'LocalTrack', 'StorageFile']:
    boundary = boundary.replace('class ' + name, 'partial class ' + name)
boundary = boundary.replace('DanmakuCalls++;',
                            'DanmakuCalls++; if (SegmentRequest != null) return SegmentRequest(cid, index);')
boundary = boundary.replace('public Task ReportHistory(PlayInfo i, double p) => Task.CompletedTask;',
                            'public Task ReportHistory(PlayInfo i, double p) { Reports.Add((i,p)); '
                            'return HistoryRequest?.Invoke(i,p) ?? Task.CompletedTask; }')
boundary = boundary.replace('var result = OpenGate == null ?',
                            'var result = OpenRequest != null ? await OpenRequest(s) : OpenGate == null ?')
boundary = boundary.replace('public int time_s;',
                            'public int time_s; public int weight=100; public string text="cue",sendID="id";')
boundary = boundary.replace('public object ShieldWords;',
                            'public List<string> ShieldWords=new(),ShieldUsers=new(),ShieldRegulars=new();')
boundary = boundary.replace('dataContext = value;',
                            'if(dataContext is System.ComponentModel.INotifyPropertyChanged old)'
                            'old.PropertyChanged-=BoundChanged; dataContext = value; '
                            'if(dataContext is System.ComponentModel.INotifyPropertyChanged current)'
                            'current.PropertyChanged+=BoundChanged; AfterContextChange?.Invoke();')
boundary = boundary.replace('static class LocalMediaTrackSelection',
                            'static partial class LocalMediaTrackSelection')
boundary = boundary.replace('public void Dispose()\n        {\n        }',
                            'public void Dispose()\n        { OnDispose?.Invoke(); }', 1)
boundary = boundary.replace('public static void Log(string m, LogType t)\n        {\n        }',
                            'public static int Calls; public static void Log(string m, LogType t)'
                            '\n        { Calls++; }')
(out / 'PlayerResidualBoundary.g.cs').write_text(boundary)
options = '\n'.join(extract(coordinator, signature, coordinator_path).replace(
    'LocalPlayInfo info', 'LocalInfo info') for signature in [
    'public static IList<LocalMediaTrackSelectionOption> VideoOptions(',
    'public static IList<LocalMediaTrackSelectionOption> AudioOptions(', 'public static string TrackLabel('
])
(out / 'PlayerResidualCoordinator.g.cs').write_text(
    'using System;using System.Threading.Tasks;using System.Collections.Generic;using System.Linq;'
    'namespace ResidualProbe {static class LocalMediaTrackSwitchCoordinator {' + coordinator_body +
    '} static partial class LocalMediaTrackSelection {\n' + options + '\n}}\n')
base_path = repo / 'src/BiliLite.UWP/Modules/IModules.cs'
child_path = repo / 'src/BiliLite.UWP/Modules/Player/InteractionVideoVM.cs'
(out / 'ActualIModules.g.cs').write_text(
    'using LogHelper = ResidualProbe.BoundaryLog;\n' + base_path.read_text(encoding='utf-8-sig'))
(out / 'player-lifetime-manifest.json').write_text(json.dumps({
    'source': str(source), 'source_sha256': sha(source.read_bytes()),
    'coordinator_source': str(coordinator_path), 'coordinator_sha256': sha(coordinator_path.read_bytes()),
    'coordinator_type_substitution': 'LocalPlayInfo -> fixture LocalInfo only',
    'residual_header_alias': 'Windows = ResidualWindows; no control method body rewrite',
    'boundary_stub_source': str(stub_path), 'boundary_stub_sha256': sha(stub_path.read_bytes()),
    'actual_child': {'source': str(child_path), 'sha256': sha(child_path.read_bytes()),
                     'compiled': 'direct complete original source'},
    'actual_base': {'source': str(base_path), 'sha256': sha(base_path.read_bytes()),
                    'header_alias_only': 'LogHelper = ResidualProbe.BoundaryLog'},
    'methods': manifest,
    'outputs': {file.name: sha(file.read_bytes()) for file in out.glob('*.g.cs')}
}, indent=2) + '\n')
